export function isKorean(locale: string | undefined = env.locale): boolean {
  return typeof locale === 'string' && /^ko(?:[-_]|$)/i.test(locale)
}

/** The dictionary for Orca's current UI language. */
export function strings(): Dictionary {
  return isKorean() ? ko : en
}

export type Strings = Dictionary
